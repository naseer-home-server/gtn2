import { createHash } from 'node:crypto'
import { spawn, execFileSync } from 'node:child_process'
import { chmod, readFile, writeFile } from 'node:fs/promises'
import net from 'node:net'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseEnv } from 'node:util'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const localFile = path.join(root, '.env.local')
// Worktrees often share the same basename. An absolute-path hash isolates Compose resources.
const workspaceId = createHash('sha256').update(root).digest('hex').slice(0, 10)
const projectName = `gtn2-${workspaceId}`
const backendFile = path.join(root, 'game/backend/.env')
const frontendFile = path.join(root, 'game/frontend/.env')
const [command = 'help', ...args] = process.argv.slice(2)

async function readEnvironment(file) {
  try { return parseEnv(await readFile(file, 'utf8')) }
  catch (error) { if (error.code === 'ENOENT') return {}; throw error }
}
async function writeEnvironment(file, values) {
  const text = '# Generated by pnpm setup:local; local to this checkout and never committed.\n'
    + Object.entries(values).map(([key, value]) => `${key}=${JSON.stringify(String(value))}`).join('\n') + '\n'
  await writeFile(file, text, { mode: 0o600 })
  await chmod(file, 0o600)
}
function portNumber(value) {
  const port = Number(value)
  if (!/^\d+$/.test(String(value)) || !Number.isInteger(port) || port < 1024 || port > 65535) {
    throw new Error(`Invalid local port: ${value}`)
  }
  return port
}
async function portAvailable(port) {
  return new Promise((resolve, reject) => {
    const server = net.createServer()
    server.once('error', (error) => {
      if (error.code === 'EADDRINUSE' || error.code === 'EACCES') resolve(false)
      else reject(error)
    })
    server.listen({ host: '127.0.0.1', port, exclusive: true }, () => server.close(() => resolve(true)))
  })
}
async function choosePort(preferred, reserved, explicit) {
  const start = portNumber(explicit ?? preferred)
  for (let port = start; port < Math.min(start + (explicit ? 1 : 1000), 65536); port++) {
    if (!reserved.has(port) && await portAvailable(port)) { reserved.add(port); return String(port) }
  }
  throw new Error(`No available local port starting at ${start}. Set POSTGRES_PORT, BACKEND_PORT, or FRONTEND_PORT explicitly.`)
}
async function sharedAuthEnvironment() {
  // Git does not copy ignored .env files into a worktree. Inherit only shared auth settings.
  try {
    const common = execFileSync('git', ['rev-parse', '--path-format=absolute', '--git-common-dir'], { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim()
    return await readEnvironment(path.join(path.dirname(common), 'game/backend/.env'))
  } catch { return {} }
}
async function configure() {
  const previous = await readEnvironment(localFile)
  const backend = await readEnvironment(backendFile)
  const frontend = await readEnvironment(frontendFile)
  const shared = await sharedAuthEnvironment()
  const sameWorkspace = previous.COMPOSE_PROJECT_NAME === projectName
  const offset = parseInt(workspaceId.slice(0, 6), 16) % 1000
  const reserved = new Set()
  const ports = {}
  for (const [key, start] of [['POSTGRES_PORT', 55000 + offset], ['BACKEND_PORT', 3000 + offset], ['FRONTEND_PORT', 5000 + offset]]) {
    ports[key] = sameWorkspace
      ? String(portNumber(previous[key]))
      : await choosePort(start, reserved, process.env[key])
    reserved.add(Number(ports[key]))
  }
  if (new Set(Object.values(ports)).size !== 3) throw new Error('Database, backend, and frontend ports must differ.')
  const auth = {}
  for (const key of ['SUPERTOKENS_CONNECTION_URI', 'SUPERTOKENS_API_KEY', 'SUPERTOKENS_DASHBOARD_ADMINS']) {
    auth[key] = process.env[key] || backend[key] || shared[key] || (key === 'SUPERTOKENS_CONNECTION_URI' ? 'http://127.0.0.1:1233' : '')
  }
  const appUrl = `http://localhost:${ports.FRONTEND_PORT}`
  await writeEnvironment(localFile, {
    COMPOSE_PROJECT_NAME: projectName, ...ports, APP_URL: appUrl,
    // Compose's app container uses the service hostname; pnpm uses the published host port.
    DATABASE_URL: 'postgresql://gtn2:gtn2@postgres:5432/gtn2',
    SUPERTOKENS_CONNECTION_URI: 'http://host.docker.internal:1233',
    SUPERTOKENS_API_KEY: auth.SUPERTOKENS_API_KEY,
    SUPERTOKENS_DASHBOARD_ADMINS: auth.SUPERTOKENS_DASHBOARD_ADMINS,
  })
  await writeEnvironment(backendFile, {
    ...backend, ...auth, LOCAL: 'true', PORT: ports.BACKEND_PORT, APP_URL: appUrl,
    DATABASE_URL: `postgresql://gtn2:gtn2@127.0.0.1:${ports.POSTGRES_PORT}/gtn2`,
  })
  await writeEnvironment(frontendFile, {
    ...frontend, VITE_LOCAL: 'true', BACKEND_PORT: ports.BACKEND_PORT, FRONTEND_PORT: ports.FRONTEND_PORT,
    BACKEND_URL: `http://127.0.0.1:${ports.BACKEND_PORT}`,
    GAME_BACKEND_URL: `http://127.0.0.1:${ports.BACKEND_PORT}`,
  })
  return readConfig()
}
async function readConfig() {
  const local = await readEnvironment(localFile)
  if (local.COMPOSE_PROJECT_NAME !== projectName) {
    throw new Error('Run pnpm setup:local in this checkout first. Each worktree needs its own generated configuration.')
  }
  for (const key of ['POSTGRES_PORT', 'BACKEND_PORT', 'FRONTEND_PORT']) portNumber(local[key])
  return local
}
function runtimeEnvironment(config) {
  return {
    ...process.env,
    LOCAL: 'true', VITE_LOCAL: 'true',
    DATABASE_URL: `postgresql://gtn2:gtn2@127.0.0.1:${config.POSTGRES_PORT}/gtn2`,
    PORT: config.BACKEND_PORT, BACKEND_PORT: config.BACKEND_PORT, FRONTEND_PORT: config.FRONTEND_PORT,
    APP_URL: config.APP_URL, GAME_BACKEND_URL: `http://127.0.0.1:${config.BACKEND_PORT}`,
  }
}
async function run(program, argv, env = process.env) {
  return new Promise((resolve, reject) => {
    const child = spawn(program, argv, { cwd: root, env, stdio: 'inherit' })
    const interrupt = () => child.kill('SIGINT')
    const terminate = () => child.kill('SIGTERM')
    process.on('SIGINT', interrupt)
    process.on('SIGTERM', terminate)
    child.once('error', reject)
    child.once('exit', (code, signal) => {
      process.off('SIGINT', interrupt)
      process.off('SIGTERM', terminate)
      if (code === 0) resolve()
      else reject(new Error(`${program} exited ${signal ? `with ${signal}` : `with code ${code}`}.`))
    })
  })
}
function compose(config, argv) {
  // Explicit naming and env-file selection avoid basename collisions and ambient deployment env.
  return run('docker', ['compose', '--project-name', projectName, '--env-file', localFile, ...argv], {
    ...process.env, ...config,
    GOOGLE_CLIENT_ID: '', GOOGLE_CLIENT_SECRET: '',
  })
}
function describe(config) {
  console.log(`Local checkout: ${root}`)
  console.log(`Compose project: ${projectName}; persistent volume: ${projectName}_postgres-data`)
  console.log(`PostgreSQL: 127.0.0.1:${config.POSTGRES_PORT}; backend: ${config.BACKEND_PORT}; app: ${config.APP_URL}`)
  console.log('SuperTokens: shared forwarded Core (start ./scripts/pf-anton once for all worktrees).')
}
async function main() {
  if (command === 'help') {
    console.log('Local commands: setup [--reset], dev, db:up, db:down, db:seed [--reset], test:db, info')
    return
  }
  if (!['setup', 'dev', 'db:up', 'db:down', 'db:seed', 'test:db', 'info'].includes(command)) throw new Error(`Unknown command: ${command}`)
  if (args.length && (!['setup', 'db:seed'].includes(command) || args.length !== 1 || args[0] !== '--reset')) throw new Error('Only setup and db:seed accept --reset.')
  if (process.env.NODE_ENV === 'production') throw new Error('Local development commands cannot run with NODE_ENV=production.')
  const config = command === 'setup' ? await configure() : await readConfig()
  if (command === 'info') { describe(config); return }
  if (command === 'db:down') { await compose(config, ['stop', 'postgres']); return }
  await compose(config, ['up', '-d', '--wait', 'postgres'])
  if (command === 'setup' || command === 'db:seed') {
    await run('pnpm', ['--filter', 'backend', 'db:seed', ...args], runtimeEnvironment(config))
    describe(config)
    if (command === 'setup') console.log('Setup complete. Run pnpm dev to start this checkout.')
  } else if (command === 'dev') {
    await run('pnpm', ['--filter', 'game', 'dev'], runtimeEnvironment(config))
  } else if (command === 'test:db') {
    await run('pnpm', ['--filter', 'backend', 'test'], { ...runtimeEnvironment(config), RUN_DB_TESTS: '1' })
  }
}
main().catch((error) => { console.error(error.message); process.exitCode = 1 })
